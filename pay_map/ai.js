const FILLER = /^(근처|주변|쪽|에서|부근|맛집|식당|음식점|집|대구|대구시)$/;

export function ruleParse(q) {
  const words = q.trim().split(/\s+/);
  const out = { area: '', mcls: [], scls: [], keywords: [], by: 'rule' };
  for (const w of words) {
    const hit = FOOD_WORDS.filter(([re]) => re.test(w));
    if (hit.length) {
      for (const [, c] of hit) { out.mcls.push(...(c.mcls ?? [])); out.scls.push(...(c.scls ?? [])); }
    } else if (!out.area && !FILLER.test(w)) {
      out.area = w.replace(/(근처|주변|쪽|에서)$/, '');
    }
  }
  out.mcls = [...new Set(out.mcls)];
  out.scls = [...new Set(out.scls)];
  return out;
}
